export const CARD_ART: Record<string, CardArtSource> = Object.fromEntries(CARD_ART_SHEETS.flatMap(sheet => sheet.cards.map((id, index) => {
    const row = Math.floor(index / 8)
    return [id, { file: sheet.file, x: index % 8 * 192 + 4, y: sheet.rows[row] + 4, width: 184, height: sheet.rows[row + 1] - sheet.rows[row] - 8 }]
})))
